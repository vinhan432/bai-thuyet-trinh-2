// Generates src/three/modelManifest.ts from the GLB files in public/models.
//
//   node tools/gen-manifest.mjs

import fs from 'node:fs';
import path from 'node:path';

const MODELS_DIR = 'public/models';
const OUT = 'src/three/modelManifest.ts';

const META = {
  bicycle: { label: 'Xe đạp Pacific Invert', kind: 'vehicle' },
  'arduino-mega': { label: 'Bo mạch Arduino Mega', kind: 'electronics' },
  wrench: { label: 'Cờ-lê hai đầu', kind: 'tool' },
  'adjustable-wrench': { label: 'Cờ-lê điều chỉnh', kind: 'tool' },
  screwdriver: { label: 'Tuốc-nơ-vít', kind: 'tool' },
  hammer: { label: 'Búa nguội', kind: 'tool' },
  handsaw: { label: 'Cưa tay', kind: 'tool' },
  'measuring-tape': { label: 'Thước cuộn', kind: 'tool' },
  'bench-vice': { label: 'Ê-tô bàn nguội', kind: 'tool' },
  drill: { label: 'Máy khoan', kind: 'tool' },
  'bolt-cutters': { label: 'Kìm cắt bu-lông', kind: 'tool' },
  'oil-can': { label: 'Bình tra dầu', kind: 'tool' },
  'tool-chest': { label: 'Tủ đồ nghề', kind: 'tool' },
  'pipe-wrench': { label: 'Cờ-lê ống nước', kind: 'tool' },
  crowbar: { label: 'Xà beng', kind: 'tool' },
  sledgehammer: { label: 'Búa tạ', kind: 'tool' },
  'circuit-board': { label: 'Bo mạch điện tử', kind: 'electronics' },
  'power-box': { label: 'Tủ điện công nghiệp', kind: 'electronics' },
  'security-camera': { label: 'Camera giám sát', kind: 'electronics' },
  laptop: { label: 'Máy tính kỹ thuật', kind: 'electronics' },
  'industrial-pipes': { label: 'Hệ ống công nghiệp', kind: 'industrial' },
  generator: { label: 'Máy phát điện', kind: 'industrial' },
  'ceiling-fan': { label: 'Quạt trần', kind: 'industrial' },
  'drill-press': { label: 'Máy khoan bàn', kind: 'tool' },
  'old-drill-press': { label: 'Máy khoan cũ', kind: 'tool' },
  'hand-plane': { label: 'Bào tay', kind: 'tool' },
  'hand-truck': { label: 'Xe đẩy hàng', kind: 'tool' },
};

const files = fs
  .readdirSync(MODELS_DIR)
  .filter((f) => f.endsWith('.glb'))
  .sort();

const entries = files.map((file) => {
  const id = path.basename(file, '.glb');
  const meta = META[id] ?? { label: id, kind: 'prop' };
  return { id, file, label: meta.label, kind: meta.kind };
});

const ids = entries.map((e) => `'${e.id}'`).join(' | ');

const lines = [
  '// AUTO-GENERATED by tools/gen-manifest.mjs — do not edit by hand.',
  '// Lists every GLB in public/models so the loader can resolve them by id.',
  '',
  `export type ModelId = ${ids};`,
  '',
  'export interface ModelEntry {',
  '  id: ModelId;',
  '  url: string;',
  '  label: string;',
  '  kind: string;',
  '}',
  '',
  'export const MODELS: Record<ModelId, ModelEntry> = {',
];

for (const e of entries) {
  lines.push(`  '${e.id}': { id: '${e.id}', url: 'models/${e.file}', label: '${e.label}', kind: '${e.kind}' },`);
}

lines.push('};', '', 'export const MODEL_IDS = Object.keys(MODELS) as ModelId[];', '');

fs.writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT}: ${entries.length} models`);
